// sprite names up to three tone ramps from palette.ts and paints with
// them: '.' empty · '1'-'4' ramps[0] shadow->highlight · '5'-'8'
// ramps[1] · '9','a','b','c' ramps[2]. One top-left light source
// across the whole set. Kept as string grids so new icons can be
// sketched in place; a unit test (src/lib/achievements.test.ts)
// enforces the 16x16 contract.

